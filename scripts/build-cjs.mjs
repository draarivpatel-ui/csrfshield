/*
 * Generate the CommonJS build from the single ESM source of truth.
 * src/index.mjs has no imports and uses no ESM-only syntax beyond export
 * declarations, so the transform stays small and auditable.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');

const EXPORT_NAMES = [
  'CODE', 'CsrfShieldError', 'base64urlEncode', 'base64urlDecodeStrict',
  'sha256', 'hmacSha256', 'constantTimeDiff', 'timingSafeEqual', 'webCrypto',
  'createNodeCrypto', 'maskToken', 'unmaskToken', 'isMaskedToken', 'parseToken',
  'parseCookieHeader', 'canonicalOrigin', 'isSafeMethod', 'createShield'
];

let body = source;
body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');
body = body.replace(/^export default [\s\S]*$/m, '');

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body.trim(),
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

const target = path.join(root, 'cjs', 'index.cjs');

if (process.argv.includes('--check')) {
  let current = null;
  try {
    current = await readFile(target, 'utf8');
  } catch (_) {
    current = null;
  }
  if (current !== output) {
    process.stderr.write('cjs/index.cjs is out of date; run npm run build:cjs\n');
    process.exit(1);
  }
  process.stdout.write('cjs/index.cjs is up to date\n');
} else {
  await writeFile(target, output, 'utf8');
  process.stdout.write('cjs/index.cjs generated from src/index.mjs\n');
}
